-- P0: lock down the ethics committee decision boundary.
--
-- This migration is deliberately additive and idempotent.  It records formal
-- committee assignment/recusal/attendance, quorum and chair confirmation,
-- keeps a structured ethics audit trail, and makes direct SQL writes obey the
-- same decision prerequisites as the HTTP controller.
BEGIN;

ALTER TABLE "伦理审查会议"
    ADD COLUMN IF NOT EXISTS "法定人数" integer NOT NULL DEFAULT 3,
    ADD COLUMN IF NOT EXISTS "表决规则" varchar(50) NOT NULL DEFAULT '有效意见过半数',
    ADD COLUMN IF NOT EXISTS "主席确认人编号" integer REFERENCES "人员"("编号"),
    ADD COLUMN IF NOT EXISTS "主席确认时间" timestamp without time zone,
    ADD COLUMN IF NOT EXISTS "主席确认说明" varchar(2000);

