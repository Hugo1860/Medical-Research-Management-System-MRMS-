-- A committee opinion is valid only when the member was formally assigned,
-- did not recuse, and was recorded as present for the same meeting.
CREATE OR REPLACE FUNCTION "tfn_伦理委员意见_正式指派校验"()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_member record;
BEGIN
    SELECT c.* INTO v_member
      FROM "伦理审查会议委员" c
     WHERE c."会议编号" = NEW."会议编号"
       AND c."委员编号" = NEW."委员编号";
    IF NOT FOUND THEN
        RAISE EXCEPTION '伦理委员意见必须由同一会议正式指派且已确认出席、未回避的委员提交';
    END IF;
    IF NEW."意见结论" = '回避' OR NEW."是否利益冲突" THEN
        IF NEW."意见结论" <> '回避' OR NEW."是否利益冲突" = false OR v_member."状态" <> '回避' OR v_member."是否回避" = false THEN
            RAISE EXCEPTION '利益冲突委员只能以回避结论登记，且必须先完成回避指派';
        END IF;
        RETURN NEW;
    END IF;
    IF v_member."状态" <> '正式指派' OR v_member."是否回避" OR v_member."出席状态" <> '出席' THEN
        RAISE EXCEPTION '伦理委员意见必须由同一会议正式指派且已确认出席、未回避的委员提交';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "trg_伦理委员意见_正式指派校验" ON "伦理审查委员意见";
CREATE TRIGGER "trg_伦理委员意见_正式指派校验"
    BEFORE INSERT OR UPDATE ON "伦理审查委员意见"
    FOR EACH ROW EXECUTE FUNCTION "tfn_伦理委员意见_正式指派校验"();

-- Formal decisions cannot be inserted directly around the workflow.  The
-- same guard is used by the controller and protects imports/SQL maintenance.
CREATE OR REPLACE FUNCTION "tfn_伦理决定_P0门禁"()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_meeting record;
    v_assigned integer;
    v_present integer;
    v_valid integer;
    v_agree integer;
    v_disagree integer;
BEGIN
    SELECT m.*, g."状态" AS agenda_status INTO v_meeting
      FROM "伦理审查会议议程" g
      JOIN "伦理审查会议" m ON m."编号" = g."会议编号"
     WHERE g."申请编号" = NEW."申请编号"
       AND g."状态" = '已审查'
       AND m."状态" = '已完成'
     ORDER BY g."编号" DESC LIMIT 1;
    IF NOT FOUND THEN
        RAISE EXCEPTION '伦理正式决定必须关联已完成且议程已审查的委员会会议';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM "伦理审查申请" a WHERE a."编号"=NEW."申请编号" AND a."状态"='审查中') THEN
        RAISE EXCEPTION '只有审查中的伦理申请可以登记正式决定';
    END IF;
    IF v_meeting."纪要状态" NOT IN ('已确认','已归档')
       OR v_meeting."主席确认人编号" IS NULL
       OR v_meeting."主席确认时间" IS NULL THEN
        RAISE EXCEPTION '伦理正式决定必须具备已确认会议纪要和主席确认';
    END IF;
    SELECT count(*)::integer INTO v_assigned
      FROM "伦理审查会议委员" c
     WHERE c."会议编号" = v_meeting."编号"
       AND c."状态" = '正式指派' AND c."是否回避" = false;
    SELECT count(*)::integer INTO v_present
      FROM "伦理审查会议委员" c
     WHERE c."会议编号" = v_meeting."编号"
       AND c."状态" = '正式指派' AND c."是否回避" = false
       AND c."出席状态" = '出席';
    SELECT count(*)::integer,
           count(*) FILTER (WHERE o."意见结论" IN ('同意','修改后同意'))::integer,
           count(*) FILTER (WHERE o."意见结论" = '不同意')::integer
      INTO v_valid, v_agree, v_disagree
      FROM "伦理审查委员意见" o
      JOIN "伦理审查会议委员" c ON c."会议编号" = o."会议编号" AND c."委员编号" = o."委员编号"
     WHERE o."申请编号" = NEW."申请编号" AND o."会议编号" = v_meeting."编号"
       AND c."状态" = '正式指派' AND c."是否回避" = false AND c."出席状态" = '出席'
       AND o."是否利益冲突" = false AND o."意见结论" <> '回避';
    IF v_present < v_meeting."法定人数" OR v_valid < v_meeting."法定人数" THEN
        RAISE EXCEPTION '伦理正式决定未达到法定人数或有效委员意见数（出席 %, 有效意见 %, 法定人数 %）', v_present, v_valid, v_meeting."法定人数";
    END IF;
    IF NEW."决定" IN ('批准','修改后批准') AND v_agree <= v_disagree THEN
        RAISE EXCEPTION '批准类伦理决定必须获得有效意见过半数同意票';
    END IF;
    IF NEW."决定" IN ('拒绝','终止') AND v_disagree <= v_agree THEN
        RAISE EXCEPTION '拒绝或终止类伦理决定必须获得有效意见过半数不同意票';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS "trg_伦理决定_P0门禁" ON "伦理审查决定";
CREATE TRIGGER "trg_伦理决定_P0门禁"
    BEFORE INSERT OR UPDATE ON "伦理审查决定"
    FOR EACH ROW EXECUTE FUNCTION "tfn_伦理决定_P0门禁"();

-- Strengthen the existing process gate.  Projects requiring ethics must have
-- a current approved application/decision and a formally archived decision.
CREATE OR REPLACE FUNCTION "sp_项目过程前置合规检查"(
    p_project_id integer,
    p_check_type character varying DEFAULT '中检'
)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE
    v_need_ethics boolean;
    v_ethics_no varchar(100);
    v_ethics_expiry date;
    v_ethics_status varchar(50);
    v_flow_template integer;
    v_approved_application bigint;
    v_approved_decision bigint;
    v_archived_decision bigint;
BEGIN
    SELECT "是否需要伦理批文", "伦理批文编号", "伦理批文有效期至", "伦理审查状态"
      INTO v_need_ethics, v_ethics_no, v_ethics_expiry, v_ethics_status
      FROM "纵向项目立项" WHERE "编号" = p_project_id;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('passed',false,'block',true,'message','未找到指定的科研课题记录');
    END IF;
    IF COALESCE(v_need_ethics,false) THEN
        IF v_ethics_status IS DISTINCT FROM '有效' OR v_ethics_no IS NULL OR btrim(v_ethics_no) = '' THEN
            RETURN jsonb_build_object('passed',false,'block',true,'check_type',p_check_type,'ethics_status',COALESCE(v_ethics_status,'待核验'),'message','合规阻断：项目尚未形成有效伦理审查状态和批件编号');
        END IF;
        IF v_ethics_expiry IS NULL OR v_ethics_expiry < CURRENT_DATE THEN
            RETURN jsonb_build_object('passed',false,'block',true,'check_type',p_check_type,'ethics_status','已过期','expiry_date',to_char(v_ethics_expiry,'YYYY-MM-DD'),'message','合规阻断：伦理批件无有效期或已过期');
        END IF;
        SELECT a."编号", a."流程模板编号" INTO v_approved_application, v_flow_template
          FROM "伦理审查申请" a
         WHERE a."项目编号" = p_project_id AND a."状态" = '已批准'
           AND a."批件编号" = v_ethics_no AND a."有效期至" >= CURRENT_DATE
         ORDER BY a."决定时间" DESC LIMIT 1;
        IF v_approved_application IS NULL THEN
            RETURN jsonb_build_object('passed',false,'block',true,'check_type',p_check_type,'message','合规阻断：未找到与项目批件一致的已批准伦理申请');
        END IF;
        SELECT d."编号" INTO v_approved_decision
          FROM "伦理审查决定" d
         WHERE d."申请编号" = v_approved_application
           AND d."决定" IN ('批准','修改后批准')
           AND d."批件编号" = v_ethics_no AND d."有效期至" >= CURRENT_DATE
         ORDER BY d."建立时间" DESC LIMIT 1;
        IF v_approved_decision IS NULL THEN
            RETURN jsonb_build_object('passed',false,'block',true,'check_type',p_check_type,'message','合规阻断：未找到已批准的伦理委员会决定');
        END IF;
        SELECT e."编号" INTO v_archived_decision
          FROM "伦理电子档案" e
         WHERE e."决定编号" = v_approved_decision AND e."档案类型" = '决定书' AND e."状态" = '已归档'
         ORDER BY e."归档时间" DESC LIMIT 1;
        IF v_archived_decision IS NULL THEN
            RETURN jsonb_build_object('passed',false,'block',true,'check_type',p_check_type,'message','合规阻断：已批准伦理决定尚未归档正式决定书');
        END IF;
    END IF;
    RETURN jsonb_build_object('passed',true,'block',false,'check_type',p_check_type,'message','前置合规性检查通过，允许继续执行');
END;
$$;

-- Renewal/amendment registration must be performed by a project-authorized
-- person and must have an ethics application in the local workflow.
CREATE OR REPLACE FUNCTION "sp_登记伦理批文续展与修正案"(p_payload jsonb)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE
    v_project_id integer := (p_payload->>'项目编号')::integer;
    v_new_no varchar(100) := NULLIF(btrim(p_payload->>'新批文编号'),'');
    v_type varchar(50) := COALESCE(NULLIF(btrim(p_payload->>'申请类型'),''),'延期续展');
    v_new_expiry date := (p_payload->>'新有效期至')::date;
    v_file_path text := NULLIF(btrim(p_payload->>'批件文件路径'),'');
    v_remark text := NULLIF(btrim(p_payload->>'变更事由与说明'),'');
    v_operator_id integer := (p_payload->>'登记人编号')::integer;
    v_old_no varchar(100);
    v_record_id bigint;
    v_application_id bigint;
    v_decision_id bigint;
BEGIN
    IF v_project_id IS NULL OR v_new_no IS NULL OR v_new_expiry IS NULL OR v_operator_id IS NULL OR v_operator_id <= 0 THEN
        RAISE EXCEPTION '项目编号、新批文编号、新有效期至和登记人编号为必填项';
    END IF;
    IF v_new_expiry < CURRENT_DATE THEN RAISE EXCEPTION '新伦理批件有效期不能早于当前日期'; END IF;
    IF v_type NOT IN ('延期续展','修正案','年度跟踪审查') THEN RAISE EXCEPTION '续展申请类型无效'; END IF;
    IF NOT EXISTS (SELECT 1 FROM "纵向项目立项" p WHERE p."编号"=v_project_id
                   AND "fn_人员可访问项目"(v_operator_id,410,v_project_id)) THEN
        RAISE EXCEPTION '登记人无权访问该纵向项目';
    END IF;
    SELECT a."编号" INTO v_application_id FROM "伦理审查申请" a
     WHERE a."项目编号"=v_project_id AND a."状态"='已批准'
       AND a."申请类型" IN ('初始审查','延期续展','修正案','年度跟踪审查')
     ORDER BY a."决定时间" DESC LIMIT 1;
    IF v_application_id IS NULL THEN RAISE EXCEPTION '项目必须先存在已批准的伦理审查申请'; END IF;
    SELECT d."编号" INTO v_decision_id FROM "伦理审查决定" d
     WHERE d."申请编号"=v_application_id AND d."决定" IN ('批准','修改后批准')
       AND d."有效期至" >= CURRENT_DATE ORDER BY d."建立时间" DESC LIMIT 1;
    IF v_decision_id IS NULL THEN RAISE EXCEPTION '续展登记必须关联已批准的伦理委员会决定'; END IF;
    IF NOT EXISTS (SELECT 1 FROM "伦理电子档案" e WHERE e."决定编号"=v_decision_id AND e."档案类型"='决定书' AND e."状态"='已归档') THEN
        RAISE EXCEPTION '续展登记必须先归档正式伦理决定书';
    END IF;
    SELECT "伦理批文编号" INTO v_old_no FROM "纵向项目立项" WHERE "编号"=v_project_id;
    INSERT INTO "伦理批件续展与修正案记录" ("项目编号","原批文编号","新批文编号","申请类型","新有效期至","批件文件路径","变更事由与说明","登记人编号")
    VALUES (v_project_id,v_old_no,v_new_no,v_type,v_new_expiry,v_file_path,v_remark,v_operator_id)
    RETURNING "编号" INTO v_record_id;
    UPDATE "纵向项目立项"
       SET "伦理批文编号"=v_new_no,"伦理批文有效期至"=v_new_expiry,"伦理批文时间"=CURRENT_TIMESTAMP,
           "伦理批文路径"=COALESCE(v_file_path,"伦理批文路径"),"伦理审查状态"='有效'
     WHERE "编号"=v_project_id;
    UPDATE "项目伦理同步记录" SET "状态"='有效',"批文编号"=v_new_no,"有效期至"=v_new_expiry,"最后同步时间"=CURRENT_TIMESTAMP WHERE "项目编号"=v_project_id;
    UPDATE "科研项目过程预警记录" SET "处理状态"='已处理/归档',"最近巡检时间"=CURRENT_TIMESTAMP WHERE "项目编号"=v_project_id AND "预警类型" IN ('伦理批件已过期阻断','伦理批件临期预警');
    RETURN jsonb_build_object('success',true,'record_id',v_record_id,'project_id',v_project_id,'new_ethics_no',v_new_no,'new_expiry',to_char(v_new_expiry,'YYYY-MM-DD'),'message','伦理批件续展/修正案登记成功，合规阻断已解除');
END;
$$;

