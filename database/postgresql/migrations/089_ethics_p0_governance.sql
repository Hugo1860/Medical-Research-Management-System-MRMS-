    DROP CONSTRAINT IF EXISTS "ck_伦理会议_法定人数",
    DROP CONSTRAINT IF EXISTS "ck_伦理会议_表决规则",
    DROP CONSTRAINT IF EXISTS "ck_伦理会议_主席确认";
