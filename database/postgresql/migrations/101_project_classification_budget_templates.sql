-- 101: 项目分类树扩展、预算科目模板、建卡模式、预算拆分规则与并发安全项目编号生成规则
BEGIN;

-- 1. 项目分类树扩展已有表字段
ALTER TABLE "项目分类"
    ADD COLUMN IF NOT EXISTS "分类编码" varchar(50),
    ADD COLUMN IF NOT EXISTS "项目性质" varchar(30) NOT NULL DEFAULT '纵向',
    ADD COLUMN IF NOT EXISTS "建卡模式" varchar(30) NOT NULL DEFAULT '单卡',
    ADD COLUMN IF NOT EXISTS "默认预算模板编号" integer,
    ADD COLUMN IF NOT EXISTS "编号规则编号" integer,
    ADD COLUMN IF NOT EXISTS "是否启用" boolean NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS "创建时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS "更新时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- 建立约束与唯一索引
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_项目分类_性质') THEN
        ALTER TABLE "项目分类" ADD CONSTRAINT "ck_项目分类_性质" CHECK ("项目性质" IN ('纵向','横向','院级'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_项目分类_建卡模式') THEN
        ALTER TABLE "项目分类" ADD CONSTRAINT "ck_项目分类_建卡模式" CHECK ("建卡模式" IN ('单卡','按经费来源拆卡','按年度拆卡','按承担单位拆卡'));
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS "uq_项目分类_编码" ON "项目分类" ("分类编码") WHERE "分类编码" IS NOT NULL;
CREATE INDEX IF NOT EXISTS "ix_项目分类_上级排序" ON "项目分类" ("上级编号", "排序");

-- 2. 预算科目模板
CREATE TABLE IF NOT EXISTS "预算科目模板" (
    "编号" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "模板编码" varchar(50) NOT NULL,
    "模板名称" varchar(100) NOT NULL,
    "版本号" integer NOT NULL DEFAULT 1,
    "适用项目性质" varchar(30) NOT NULL DEFAULT '纵向',
    "间接费比例上限" numeric(5,2) NOT NULL DEFAULT 30.00,
    "状态" varchar(20) NOT NULL DEFAULT '草稿',
    "备注" varchar(500),
    "创建人编号" integer NOT NULL REFERENCES "人员"("编号"),
    "创建时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "更新时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_预算科目模板_编码版本" UNIQUE ("模板编码", "版本号"),
    CONSTRAINT "ck_预算科目模板_性质" CHECK ("适用项目性质" IN ('纵向','横向','院级')),
    CONSTRAINT "ck_预算科目模板_状态" CHECK ("状态" IN ('草稿','启用','停用')),
    CONSTRAINT "ck_预算科目模板_间接费上限" CHECK ("间接费比例上限" >= 0 AND "间接费比例上限" <= 100)
);

-- 3. 预算科目模板明细
CREATE TABLE IF NOT EXISTS "预算科目模板明细" (
    "编号" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "模板编号" integer NOT NULL REFERENCES "预算科目模板"("编号") ON DELETE CASCADE,
    "科目编码" varchar(50) NOT NULL,
    "科目名称" varchar(100) NOT NULL,
    "上级科目编码" varchar(50),
    "比例上限" numeric(5,2),
    "是否间接费" boolean NOT NULL DEFAULT FALSE,
    "是否允许调剂" boolean NOT NULL DEFAULT TRUE,
    "排序" integer NOT NULL DEFAULT 0,
    CONSTRAINT "uq_预算科目明细_模板科目" UNIQUE ("模板编号", "科目编码"),
    CONSTRAINT "ck_预算科目明细_比例" CHECK ("比例上限" IS NULL OR ("比例上限" >= 0 AND "比例上限" <= 100))
);
CREATE INDEX IF NOT EXISTS "ix_预算科目明细_模板" ON "预算科目模板明细" ("模板编号", "排序");

-- 4. 预算拆分规则
CREATE TABLE IF NOT EXISTS "预算拆分规则" (
    "编号" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "模板编号" integer NOT NULL REFERENCES "预算科目模板"("编号") ON DELETE CASCADE,
    "拆分维度" varchar(30) NOT NULL,
    "规则配置" jsonb NOT NULL DEFAULT '{}'::jsonb,
    "是否启用" boolean NOT NULL DEFAULT TRUE,
    "创建时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "ck_预算拆分规则_维度" CHECK ("拆分维度" IN ('年度','经费来源','承担单位','科目'))
);

-- 5. 项目编号规则
CREATE TABLE IF NOT EXISTS "项目编号规则" (
    "编号" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "规则编码" varchar(50) NOT NULL,
    "规则名称" varchar(100) NOT NULL,
    "前缀" varchar(30) NOT NULL,
    "日期格式" varchar(20) NOT NULL DEFAULT 'YYYY',
    "流水位数" integer NOT NULL DEFAULT 4,
    "重置周期" varchar(20) NOT NULL DEFAULT '年',
    "当前周期" varchar(20),
    "当前流水" integer NOT NULL DEFAULT 0,
    "创建时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "更新时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_项目编号规则_编码" UNIQUE ("规则编码"),
    CONSTRAINT "ck_项目编号规则_日期格式" CHECK ("日期格式" IN ('YYYY','YYYYMM','YY','无')),
    CONSTRAINT "ck_项目编号规则_流水位数" CHECK ("流水位数" BETWEEN 3 AND 8),
    CONSTRAINT "ck_项目编号规则_重置周期" CHECK ("重置周期" IN ('年','月','不重置'))
);

-- 6. 并发安全项目编号生成函数
CREATE OR REPLACE FUNCTION "fn_生成项目编号"(p_规则编码 varchar)
RETURNS varchar(100) LANGUAGE plpgsql AS $$
DECLARE
    r record;
    v_target_period varchar(20);
    v_now timestamp := CURRENT_TIMESTAMP;
    v_next_seq integer;
    v_code varchar(100);
BEGIN
    SELECT * INTO r FROM "项目编号规则" WHERE "规则编码" = p_规则编码 FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION '未找到项目编号规则: %', p_规则编码;
    END IF;

    -- 计算目标周期
    IF r."重置周期" = '年' THEN
        v_target_period := to_char(v_now, 'YYYY');
    ELSIF r."重置周期" = '月' THEN
        v_target_period := to_char(v_now, 'YYYYMM');
    ELSE
        v_target_period := 'PERPETUAL';
    END IF;

    IF r."当前周期" IS NULL OR r."当前周期" <> v_target_period THEN
        v_next_seq := 1;
    ELSE
        v_next_seq := r."当前流水" + 1;
    END IF;

    UPDATE "项目编号规则"
    SET "当前周期" = v_target_period,
        "当前流水" = v_next_seq,
        "更新时间" = CURRENT_TIMESTAMP
    WHERE "编号" = r."编号";

    -- 格式化编号
    v_code := r."前缀";
    IF r."日期格式" = 'YYYY' THEN
        v_code := v_code || to_char(v_now, 'YYYY');
    ELSIF r."日期格式" = 'YYYYMM' THEN
        v_code := v_code || to_char(v_now, 'YYYYMM');
    ELSIF r."日期格式" = 'YY' THEN
        v_code := v_code || to_char(v_now, 'YY');
    END IF;

    v_code := v_code || lpad(v_next_seq::text, r."流水位数", '0');
    RETURN v_code;
END;
$$;

