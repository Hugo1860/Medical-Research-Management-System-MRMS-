-- P1: 完善独立伦理委员会流程：会议排期、议程、会议纪要和正式电子档案。
-- 074 已提供会议基础表；本迁移仅增加可审计的业务关系和归档对象，不改变既有申请状态。
BEGIN;

ALTER TABLE "伦理审查会议"
    ADD COLUMN IF NOT EXISTS "议程说明" text,
    ADD COLUMN IF NOT EXISTS "纪要状态" varchar(20) NOT NULL DEFAULT '未开始',
    ADD COLUMN IF NOT EXISTS "纪要提交时间" timestamp without time zone,
    ADD COLUMN IF NOT EXISTS "纪要确认时间" timestamp without time zone,
    ADD COLUMN IF NOT EXISTS "纪要确认人编号" integer REFERENCES "人员"("编号");

ALTER TABLE "伦理审查会议"
    DROP CONSTRAINT IF EXISTS "ck_伦理会议_纪要状态";
ALTER TABLE "伦理审查会议"
    ADD CONSTRAINT "ck_伦理会议_纪要状态"
    CHECK ("纪要状态" IN ('未开始','草稿','待确认','已确认','已归档'));

CREATE TABLE IF NOT EXISTS "伦理审查会议议程" (
    "编号" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "会议编号" bigint NOT NULL REFERENCES "伦理审查会议"("编号") ON DELETE CASCADE,
    "申请编号" bigint NOT NULL REFERENCES "伦理审查申请"("编号") ON DELETE RESTRICT,
    "排序号" integer NOT NULL DEFAULT 1,
    "议题说明" varchar(2000),
    "状态" varchar(20) NOT NULL DEFAULT '已排期',
    "建立人编号" integer NOT NULL REFERENCES "人员"("编号"),
    "建立时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_伦理会议议程_会议申请" UNIQUE ("会议编号","申请编号"),
    CONSTRAINT "ck_伦理会议议程_排序" CHECK ("排序号" > 0),
    CONSTRAINT "ck_伦理会议议程_状态" CHECK ("状态" IN ('已排期','已审查','已撤回'))
);
CREATE INDEX IF NOT EXISTS "ix_伦理会议议程_会议排序"
    ON "伦理审查会议议程" ("会议编号","排序号");
CREATE INDEX IF NOT EXISTS "ix_伦理会议议程_申请"
    ON "伦理审查会议议程" ("申请编号","状态");

CREATE TABLE IF NOT EXISTS "伦理审查会议纪要" (
    "编号" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "会议编号" bigint NOT NULL REFERENCES "伦理审查会议"("编号") ON DELETE CASCADE,
    "纪要正文" text NOT NULL,
    "出席委员摘要" text,
    "决议摘要" text,
    "附件路径" text,
    "状态" varchar(20) NOT NULL DEFAULT '草稿',
    "记录人编号" integer NOT NULL REFERENCES "人员"("编号"),
    "确认人编号" integer REFERENCES "人员"("编号"),
    "确认时间" timestamp without time zone,
    "建立时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "更新时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_伦理会议纪要_会议" UNIQUE ("会议编号"),
    CONSTRAINT "ck_伦理会议纪要_状态" CHECK ("状态" IN ('草稿','待确认','已确认','已归档')),
    CONSTRAINT "ck_伦理会议纪要_确认信息" CHECK (("状态" IN ('草稿','待确认') AND "确认人编号" IS NULL AND "确认时间" IS NULL) OR ("状态" IN ('已确认','已归档') AND "确认人编号" IS NOT NULL AND "确认时间" IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS "伦理电子档案" (
    "编号" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "申请编号" bigint REFERENCES "伦理审查申请"("编号") ON DELETE RESTRICT,
    "会议编号" bigint REFERENCES "伦理审查会议"("编号") ON DELETE RESTRICT,
    "决定编号" bigint REFERENCES "伦理审查决定"("编号") ON DELETE RESTRICT,
    "档案类型" varchar(30) NOT NULL,
    "文件名称" varchar(255),
    "文件路径" text NOT NULL,
    "文件校验值" varchar(128),
    "状态" varchar(20) NOT NULL DEFAULT '待归档',
    "备注" varchar(2000),
    "归档人编号" integer REFERENCES "人员"("编号"),
    "归档时间" timestamp without time zone,
    "建立人编号" integer NOT NULL REFERENCES "人员"("编号"),
    "建立时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "ck_伦理电子档案_对象" CHECK ("申请编号" IS NOT NULL OR "会议编号" IS NOT NULL OR "决定编号" IS NOT NULL),
    CONSTRAINT "ck_伦理电子档案_类型" CHECK ("档案类型" IN ('申请材料','会议议程','会议纪要','决定书','持续审查','不良事件','修正案','其他')),
    CONSTRAINT "ck_伦理电子档案_状态" CHECK (("状态"='待归档' AND "归档人编号" IS NULL AND "归档时间" IS NULL) OR ("状态"='已归档' AND "归档人编号" IS NOT NULL AND "归档时间" IS NOT NULL) OR "状态"='已作废')
);
CREATE INDEX IF NOT EXISTS "ix_伦理电子档案_申请状态"
    ON "伦理电子档案" ("申请编号","状态","档案类型");
CREATE INDEX IF NOT EXISTS "ix_伦理电子档案_会议状态"
    ON "伦理电子档案" ("会议编号","状态","档案类型");

COMMENT ON TABLE "伦理审查会议议程" IS '伦理委员会会议排期与申请议程关系，申请进入审查会议后方可绑定委员意见';
COMMENT ON TABLE "伦理审查会议纪要" IS '伦理委员会会议纪要，确认后才能进入正式电子档案';
COMMENT ON TABLE "伦理电子档案" IS '伦理申请、会议、决定和持续审查材料的正式归档索引，文件内容存储在受控文件服务';

UPDATE "系统迁移版本"
   SET "版本" = 81,
       "脚本" = '081_ethics_committee_archive.sql',
       "检查摘要" = '补齐伦理委员会会议排期、议程、会议纪要和正式电子档案归档',
       "应用时间" = CURRENT_TIMESTAMP
 WHERE "编号" = 1;

COMMIT;
