-- P1: 扩展人员科研能力画像、可用时间和团队匹配索引。
-- 以 048 的能力画像表为基础，保留自由文本兼容历史数据；标签表用于
-- 可解释的检索和匹配，所有匹配结果仍需业务人员确认后才能加入项目。
BEGIN;

ALTER TABLE "人员科研能力"
    ADD COLUMN IF NOT EXISTS "可用时间" varchar(1000),
    ADD COLUMN IF NOT EXISTS "每周可用小时" numeric(5,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "可承担项目数" integer NOT NULL DEFAULT 3,
    ADD COLUMN IF NOT EXISTS "当前可接项目" boolean NOT NULL DEFAULT TRUE;

ALTER TABLE "人员科研能力"
    DROP CONSTRAINT IF EXISTS "ck_人员科研能力_每周可用小时";
ALTER TABLE "人员科研能力"
    ADD CONSTRAINT "ck_人员科研能力_每周可用小时"
        CHECK ("每周可用小时" >= 0 AND "每周可用小时" <= 168);
ALTER TABLE "人员科研能力"
    DROP CONSTRAINT IF EXISTS "ck_人员科研能力_可承担项目数";
ALTER TABLE "人员科研能力"
    ADD CONSTRAINT "ck_人员科研能力_可承担项目数"
        CHECK ("可承担项目数" >= 0 AND "可承担项目数" <= 100);

CREATE INDEX IF NOT EXISTS "ix_人员科研能力_可接项目"
    ON "人员科研能力" ("当前可接项目", "合作意愿", "每周可用小时" DESC);

CREATE TABLE IF NOT EXISTS "人员能力标签" (
    "编号" bigint GENERATED BY DEFAULT AS IDENTITY,
    "人员编号" integer NOT NULL,
    "标签类型" varchar(20) NOT NULL,
    "标签" varchar(100) NOT NULL,
    "来源" varchar(20) NOT NULL DEFAULT '人员维护',
    "建立人编号" integer NOT NULL,
    "建立时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "pk_人员能力标签" PRIMARY KEY ("编号"),
    CONSTRAINT "uq_人员能力标签_人员类型标签" UNIQUE ("人员编号", "标签类型", "标签"),
    CONSTRAINT "ck_人员能力标签_类型" CHECK ("标签类型" IN ('研究专长','技术服务')),
    CONSTRAINT "ck_人员能力标签_来源" CHECK ("来源" IN ('人员维护','管理员维护','HR同步'))
);

CREATE INDEX IF NOT EXISTS "ix_人员能力标签_类型标签"
    ON "人员能力标签" ("标签类型", "标签");
CREATE INDEX IF NOT EXISTS "ix_人员能力标签_人员"
    ON "人员能力标签" ("人员编号", "标签类型");

-- 通过团队成员和项目分工表建立可复用的只读查询视图，避免匹配逻辑
-- 依赖某一类项目表，纵向/横向项目均可由流程模板编号区分。
CREATE OR REPLACE VIEW "v1_人员团队项目分工" AS
SELECT tm."团队编号", t."团队名称", tm."人员编号", p."姓名", tm."成员角色", tm."状态" AS "成员状态",
       a."流程模板编号", a."项目编号", a."分工类型", a."工作量占比", a."状态" AS "分工状态",
       a."开始日期", a."结束日期", a."备注"
  FROM "科研团队成员" tm
  JOIN "科研团队" t ON t."编号" = tm."团队编号"
  JOIN "人员" p ON p."编号" = tm."人员编号"
  LEFT JOIN "人员项目分工" a ON a."人员编号" = tm."人员编号"
 WHERE tm."状态" = '有效';

UPDATE "系统迁移版本"
   SET "版本" = 79,
       "脚本" = '079_people_team_expertise.sql',
       "检查摘要" = '扩展人员科研能力可用时间、能力标签及团队项目分工查询视图',
       "应用时间" = CURRENT_TIMESTAMP
 WHERE "编号" = 1;

COMMIT;
