-- 补齐纵向项目申报详情视图：与 v2_纵向项目申报 字段完全一致，匹配 C# 模型 v2_纵向项目申报_详情
CREATE OR REPLACE VIEW "v2_纵向项目申报_详情" AS
SELECT "a"."编号", "a"."分类", "a"."项目名称", "a"."申报人编号", "b"."工号", "b"."姓名", "b"."部门编号", "b"."部门名称",
       "a"."学科门类", "a"."学科类型", "a"."申报年度", "a"."项目类型", "a"."项目级别", "a"."项目来源单位", "a"."项目类别",
