-- 8. 存储过程：自动匹配论文期刊分区与影响因子 (支持采集结果或在库论文)
CREATE OR REPLACE FUNCTION sp_自动匹配论文期刊分区与影响因子(
    p_采集结果编号 bigint DEFAULT NULL,
    p_论文编号 integer DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_journal_id integer;
    v_journal_name character varying(500);
    v_issn character varying(50);
    v_cn character varying(50);
    v_cas_part character varying(50);
    v_cas_subject character varying(100);
    v_is_top boolean := false;
    v_if numeric(18,3);
    v_jcr character varying(50);
    v_matched_name character varying(500);
BEGIN
    IF p_采集结果编号 IS NOT NULL THEN
        SELECT "刊物名称", "ISSN号", "CN号"
          INTO v_journal_name, v_issn, v_cn
          FROM "论文采集结果"
         WHERE "编号" = p_采集结果编号;
    ELSIF p_论文编号 IS NOT NULL THEN
        SELECT p."刊物编号", j."名称", j."ISSN号", j."CN号"
          INTO v_journal_id, v_journal_name, v_issn, v_cn
          FROM "成果论文" p
          LEFT JOIN "期刊" j ON j."编号" = p."刊物编号"
         WHERE p."编号" = p_论文编号;
    ELSE
        RETURN jsonb_build_object('success', false, 'message', '必须提供采集结果编号或论文编号');
    END IF;

    -- 在 25,000+ 期刊库中按 ISSN/CN/刊名双向智能匹配
    SELECT j."编号", j."名称", j."中科院分区", j."中科院大类学科", j."是否Top期刊", j."影响因子", j."JCR分区"
      INTO v_journal_id, v_matched_name, v_cas_part, v_cas_subject, v_is_top, v_if, v_jcr
      FROM "期刊" j
     WHERE (v_issn IS NOT NULL AND btrim(v_issn) <> '' AND replace(replace(COALESCE(j."ISSN号",''),'-',''),' ','') = replace(replace(v_issn,'-',''),' ',''))
        OR (v_cn IS NOT NULL AND btrim(v_cn) <> '' AND replace(replace(COALESCE(j."CN号",''),'-',''),' ','') = replace(replace(v_cn,'-',''),' ',''))
        OR (v_journal_name IS NOT NULL AND lower(COALESCE(j."名称",'')) = lower(btrim(v_journal_name)))
        OR (v_journal_name IS NOT NULL AND lower(COALESCE(j."英文刊名",'')) = lower(btrim(v_journal_name)))
        OR (v_journal_name IS NOT NULL AND length(btrim(v_journal_name)) >= 4 AND (j."名称" ILIKE '%' || btrim(v_journal_name) || '%' OR j."英文刊名" ILIKE '%' || btrim(v_journal_name) || '%'))
     ORDER BY 
       CASE
         WHEN v_issn IS NOT NULL AND replace(replace(COALESCE(j."ISSN号",''),'-',''),' ','') = replace(replace(v_issn,'-',''),' ','') THEN 100
         WHEN v_cn IS NOT NULL AND replace(replace(COALESCE(j."CN号",''),'-',''),' ','') = replace(replace(v_cn,'-',''),' ','') THEN 95
         WHEN v_journal_name IS NOT NULL AND (lower(COALESCE(j."名称",'')) = lower(btrim(v_journal_name)) OR lower(COALESCE(j."英文刊名",'')) = lower(btrim(v_journal_name))) THEN 90
         ELSE 60
       END DESC,
       j."影响因子" DESC NULLS LAST,
       j."年度" DESC NULLS LAST,
       j."编号" DESC
     LIMIT 1;

    -- 只有真实期刊库记录中的元数据才可回写；缺失或未匹配时保留空值并要求人工核验。
    IF v_journal_id IS NOT NULL THEN
        IF p_采集结果编号 IS NOT NULL THEN
            UPDATE "论文采集结果"
               SET "中科院分区" = v_cas_part,
                   "中科院大类学科" = v_cas_subject,
                   "是否Top期刊" = COALESCE(v_is_top, false),
                   "影响因子" = v_if,
                   "JCR分区" = v_jcr
             WHERE "编号" = p_采集结果编号;
        END IF;
        IF p_论文编号 IS NOT NULL THEN
            UPDATE "成果论文"
               SET "刊物编号" = COALESCE("刊物编号", v_journal_id),
                   "中科院分区" = v_cas_part,
                   "中科院大类学科" = v_cas_subject,
                   "是否Top期刊" = COALESCE(v_is_top, false),
                   "影响因子" = v_if,
                   "JCR分区" = v_jcr
             WHERE "编号" = p_论文编号;
        END IF;
        IF v_cas_part IS NULL OR v_cas_subject IS NULL OR v_if IS NULL OR v_jcr IS NULL THEN
            RETURN jsonb_build_object('success', false, 'journal_id', v_journal_id,
                'matched_journal_name', v_matched_name, 'message', '期刊已匹配但元数据不完整，状态待核验');
        END IF;
        RETURN jsonb_build_object('success', true, 'journal_id', v_journal_id,
            'matched_journal_name', v_matched_name, 'cas_partition', v_cas_part,
            'cas_subject', v_cas_subject, 'is_top', COALESCE(v_is_top, false),
            'impact_factor', v_if, 'jcr_partition', v_jcr);
    END IF;

    IF p_采集结果编号 IS NOT NULL THEN
        UPDATE "论文采集结果"
           SET "中科院分区" = NULL, "中科院大类学科" = NULL,
               "是否Top期刊" = false, "影响因子" = NULL, "JCR分区" = NULL,
               "网推状态" = '低置信度候选', "消歧命中依据" = '未匹配期刊元数据，待人工核验'
         WHERE "编号" = p_采集结果编号;
    END IF;
    RETURN jsonb_build_object('success', false, 'journal_id', NULL,
        'message', '未匹配期刊元数据，状态待核验');
END;
$$;

-- 9. 存储过程：大数据智能消歧算法与主动网推推荐度计算
CREATE OR REPLACE FUNCTION sp_论文网推消歧与智能推荐(
    p_采集结果编号 bigint
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
    v_raw_text text;
    v_alias_hit boolean := false;
    v_matched_alias character varying(300);
    v_matched_person_id integer;
    v_matched_person_name character varying(50);
    v_matched_scholar_alias character varying(200);
    v_dept_name character varying(100);
    v_score numeric(5,2) := 0;
    v_reason text := '';
    v_push_status character varying(50) := '普通待认领';
BEGIN
    SELECT * INTO r FROM "论文采集结果" WHERE "编号" = p_采集结果编号;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', '采集结果未找到');
    END IF;

    v_raw_text := COALESCE(r."原始数据"::text, '') || ' ' || COALESCE(r."作者", '') || ' ' || COALESCE(r."论文标题", '');

    -- 阶段 A：医院机构规范名与别名匹配 (+45 分)
    SELECT a."别名", true
      INTO v_matched_alias, v_alias_hit
      FROM "科研单位别名" a
     WHERE a."是否启用" = true
       AND v_raw_text ILIKE '%' || a."别名" || '%'
     LIMIT 1;

    IF v_alias_hit THEN
        v_score := v_score + 45;
        v_reason := v_reason || '机构别名命中【' || v_matched_alias || '】; ';
    ELSE
        -- 没有登记的真实机构别名时不按通用词加分，避免把不确定来源当作本院成果。
        v_reason := v_reason || '未命中机构规范别名; ';
    END IF;

    -- 阶段 B：学者中英文拼音署名消歧匹配 (+35 分)
    SELECT x."人员编号", x."姓名", x."英文拼音署名", x."科室名称"
      INTO v_matched_person_id, v_matched_person_name, v_matched_scholar_alias, v_dept_name
      FROM "学者署名消歧库" x
     WHERE (
           r."作者" ILIKE '%' || x."英文拼音署名" || '%'
        OR r."作者" ILIKE '%' || x."姓名" || '%'
        OR v_raw_text ILIKE '%' || x."英文拼音署名" || '%'
        OR v_raw_text ILIKE '%' || x."姓名" || '%'
     )
     ORDER BY length(x."英文拼音署名") DESC
     LIMIT 1;

    IF v_matched_person_id IS NOT NULL THEN
        v_score := v_score + 35;
        v_reason := v_reason || '学者拼音署名命中【' || v_matched_scholar_alias || ' (' || v_matched_person_name || ')】; ';

        -- 阶段 C：承研科室协同消歧 (+10 分)
        IF v_dept_name IS NOT NULL AND length(v_dept_name) > 1 AND v_raw_text ILIKE '%' || v_dept_name || '%' THEN
            v_score := v_score + 10;
            v_reason := v_reason || '承研科室命中【' || v_dept_name || '】; ';
        END IF;

        -- 阶段 D：首要/通讯作者权重加成 (+10 分)
        IF r."作者" IS NOT NULL AND (
           r."作者" ILIKE v_matched_scholar_alias || '%'
           OR r."作者" ILIKE '%' || v_matched_scholar_alias || '*%'
           OR r."作者" ILIKE '%' || v_matched_scholar_alias || ' (corresponding)%'
        ) THEN
            v_score := v_score + 10;
            v_reason := v_reason || '处于第一/通讯作者核心位次; ';
        END IF;
    ELSE
        -- 未命中真实署名时不得把成果分配给管理员或首个用户；保留待核验状态并返回失败。
        v_push_status := '低置信度候选';
        v_reason := '未命中人员署名消歧记录，待人工核验';
        UPDATE "论文采集结果"
           SET "推荐认领人编号" = NULL,
               "推荐认领人姓名" = NULL,
               "消歧置信度" = 0,
               "消歧命中依据" = v_reason,
               "网推状态" = v_push_status
         WHERE "编号" = p_采集结果编号;
        RETURN jsonb_build_object('success', false, 'record_id', p_采集结果编号,
            'person_id', NULL, 'person_name', NULL, 'score', 0,
            'push_status', v_push_status, 'reason', v_reason);
    END IF;

    v_score := LEAST(100, v_score);

    IF v_score >= 75 THEN
        v_push_status := '高置信度网推';
    ELSIF v_score >= 40 THEN
        v_push_status := '普通待认领';
    ELSE
        v_push_status := '低置信度候选';
    END IF;

    -- 回写消歧打标与网推结论
    UPDATE "论文采集结果"
       SET "推荐认领人编号" = v_matched_person_id,
           "推荐认领人姓名" = v_matched_person_name,
           "消歧置信度" = v_score,
           "消歧命中依据" = btrim(v_reason),
           "网推状态" = v_push_status
     WHERE "编号" = p_采集结果编号;

    RETURN jsonb_build_object(
        'success', true,
        'record_id', p_采集结果编号,
        'person_id', v_matched_person_id,
        'person_name', v_matched_person_name,
        'score', v_score,
        'push_status', v_push_status,
        'reason', v_reason
    );
END;
$$;

-- 10. 存储过程：触发论文全网主动网推扫描与批量打标
CREATE OR REPLACE FUNCTION sp_触发论文全网主动网推(
    p_外部系统编号 bigint DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
    v_total_scanned integer := 0;
    v_high_confidence integer := 0;
    v_partition_matched integer := 0;
    v_disambig_res jsonb;
    v_part_res jsonb;
BEGIN
    FOR r IN
        SELECT "编号"
          FROM "论文采集结果"
         WHERE "状态" = '待认领'
           AND (p_外部系统编号 IS NULL OR "外部系统编号" = p_外部系统编号)
         ORDER BY "编号" ASC
    LOOP
        v_total_scanned := v_total_scanned + 1;

        -- 1. 匹配中科院期刊分区与影响因子
        v_part_res := sp_自动匹配论文期刊分区与影响因子(r."编号", NULL);
        IF (v_part_res->>'success')::boolean THEN
            v_partition_matched := v_partition_matched + 1;
        END IF;

        -- 2. 机构与学者别名消歧
        v_disambig_res := sp_论文网推消歧与智能推荐(r."编号");
        IF (v_disambig_res->>'push_status') = '高置信度网推' THEN
            v_high_confidence := v_high_confidence + 1;
        END IF;
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'total_scanned', v_total_scanned,
        'high_confidence_pushed', v_high_confidence,
        'partition_matched', v_partition_matched,
        'message', format('全网论文主动网推完成：共巡检消歧 %s 篇论文，识别中科院分区 %s 篇，生成高置信度主动网推待办 %s 篇。', v_total_scanned, v_partition_matched, v_high_confidence)
    );
END;
$$;

-- 11. 存储过程：一键确认认领网推论文
CREATE OR REPLACE FUNCTION sp_一键确认认领网推论文(
    p_采集结果编号 bigint,
    p_认领人编号 integer,
    p_作者位次 character varying(50) DEFAULT '第一作者',
    p_认领说明 text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    r RECORD;
    v_paper_id integer;
    v_person_name character varying(50);
BEGIN
    SELECT * INTO r FROM "论文采集结果" WHERE "编号" = p_采集结果编号;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', '论文采集结果未找到');
    END IF;

    SELECT "姓名" INTO v_person_name FROM "人员" WHERE "编号" = p_认领人编号 AND "是否启用" = true;
    IF v_person_name IS NULL THEN
        RETURN jsonb_build_object('success', false, 'message', '认领人必须对应启用的真实人员');
    END IF;

    v_paper_id := r."论文编号";

    -- 如果尚未建立正式成果论文，则创建入库并继承中科院分区与影响因子
    IF v_paper_id IS NULL OR v_paper_id = 0 THEN
        INSERT INTO "成果论文" (
            "认领人编号", "论文标题", "年度", "中科院分区", "中科院大类学科", "是否Top期刊", "影响因子", "JCR分区", "备注"
        )
        VALUES (
            p_认领人编号, r."论文标题", EXTRACT(YEAR FROM CURRENT_DATE)::integer,
            r."中科院分区", r."中科院大类学科", r."是否Top期刊", r."影响因子", r."JCR分区",
            COALESCE(p_认领说明, '主动大数据网推认领')
        )
        RETURNING "编号" INTO v_paper_id;
    ELSE
        UPDATE "成果论文"
           SET "认领人编号" = p_认领人编号,
               "中科院分区" = COALESCE("中科院分区", r."中科院分区"),
               "中科院大类学科" = COALESCE("中科院大类学科", r."中科院大类学科"),
               "是否Top期刊" = COALESCE("是否Top期刊", r."是否Top期刊"),
               "影响因子" = COALESCE("影响因子", r."影响因子"),
               "JCR分区" = COALESCE("JCR分区", r."JCR分区")
         WHERE "编号" = v_paper_id;
    END IF;

    -- 记录/更新成果作者
    INSERT INTO "成果作者" ("成果类型", "成果编号", "作者级别", "作者编号")
    VALUES (1, v_paper_id, COALESCE(p_作者位次, '第一作者'), p_认领人编号)
    ON CONFLICT DO NOTHING;

    -- 更新论文采集结果表状态为已认领
    UPDATE "论文采集结果"
       SET "状态" = '已认领',
           "网推状态" = '已认领',
           "论文编号" = v_paper_id,
           "最后同步时间" = CURRENT_TIMESTAMP
     WHERE "编号" = p_采集结果编号;

    RETURN jsonb_build_object(
        'success', true,
        'paper_id', v_paper_id,
        'claimant_id', p_认领人编号,
        'claimant_name', v_person_name,
        'message', format('论文【%s】已成功认领归档至学者学术档案！', r."论文标题")
    );
END;
$$;

