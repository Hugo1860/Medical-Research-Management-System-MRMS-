-- P0：基层/二级核心版能力开关、项目闭环验收、外部接口真实状态和孤立绑定人工确认。
BEGIN;

-- 医院模式不再只依赖隐藏菜单；功能开关由服务端读取并作为业务边界依据。
ALTER TABLE "医院运营配置"
    ADD COLUMN IF NOT EXISTS "启用功能" jsonb NOT NULL DEFAULT '{
      "projectLifecycle": true,
      "financeCore": true,
      "ethics": true,
      "achievements": true,
      "notifications": true,
      "basicStatistics": true,
      "externalIntegration": true,
      "advancedModules": true
    }'::jsonb,
    ADD COLUMN IF NOT EXISTS "配置版本" integer NOT NULL DEFAULT 1;

UPDATE "医院运营配置"
   SET "启用功能" = CASE WHEN "运营模式" = '二级精简' THEN
       '{
         "projectLifecycle": true,
         "financeCore": true,
         "ethics": true,
         "achievements": true,
         "notifications": true,
         "basicStatistics": true,
         "externalIntegration": false,
         "advancedModules": false
       }'::jsonb
       ELSE '{
         "projectLifecycle": true,
         "financeCore": true,
         "ethics": true,
         "achievements": true,
         "notifications": true,
         "basicStatistics": true,
         "externalIntegration": true,
         "advancedModules": true
       }'::jsonb END,
       "配置版本" = 2
 WHERE COALESCE("配置版本", 1) < 2;

-- 外部系统状态只由连接测试/worker 回写，不能以“是否启用”冒充已连接。
ALTER TABLE "外部系统"
    ADD COLUMN IF NOT EXISTS "接入方式" varchar(20) NOT NULL DEFAULT '接口',
    ADD COLUMN IF NOT EXISTS "最近连接状态" varchar(20) NOT NULL DEFAULT '未测试',
    ADD COLUMN IF NOT EXISTS "最近连接时间" timestamp without time zone,
    ADD COLUMN IF NOT EXISTS "最近连接错误" varchar(2000),
    ADD CONSTRAINT "ck_外部系统_接入方式" CHECK ("接入方式" IN ('接口','人工导入')),
    ADD CONSTRAINT "ck_外部系统_最近连接状态" CHECK ("最近连接状态" IN ('未测试','已连接','失败'));

-- 迁移异常的人工确认记录。确认只记录业务决定，不自动删除或猜测修复原绑定。
CREATE TABLE IF NOT EXISTS "项目参与人绑定复核" (
    "编号" bigint GENERATED BY DEFAULT AS IDENTITY,
    "参与人记录编号" integer NOT NULL,
    "确认流程模板编号" integer NOT NULL,
    "确认说明" varchar(1000) NOT NULL,
    "复核状态" varchar(20) NOT NULL DEFAULT '已确认',
    "复核人编号" integer NOT NULL REFERENCES "人员"("编号"),
    "复核时间" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "pk_项目参与人绑定复核" PRIMARY KEY ("编号"),
    CONSTRAINT "fk_项目参与人绑定复核_记录" FOREIGN KEY ("参与人记录编号") REFERENCES "项目参与人"("编号"),
    CONSTRAINT "uq_项目参与人绑定复核_记录" UNIQUE ("参与人记录编号"),
    CONSTRAINT "ck_项目参与人绑定复核_流程" CHECK ("确认流程模板编号" IN (400,410,450)),
    CONSTRAINT "ck_项目参与人绑定复核_状态" CHECK ("复核状态" IN ('已确认','拒绝修复')),
    CONSTRAINT "ck_项目参与人绑定复核_说明" CHECK (length(btrim("确认说明")) > 0)
);

CREATE INDEX IF NOT EXISTS "ix_项目参与人绑定复核_流程"
    ON "项目参与人绑定复核" ("确认流程模板编号", "复核时间" DESC);

-- 项目闭环的只读验收视图。金额来自本地业务事实，外部回执仍由外部系统状态单独表达。
CREATE OR REPLACE VIEW "v_科研项目核心闭环" AS
SELECT
    l."编号" AS "立项编号",
    l."项目中文名称" AS "项目名称",
    l."负责人编号",
    CASE WHEN EXISTS (
        SELECT 1 FROM "流程" f
         WHERE f."流程模板编号" = 410 AND f."项目编号" = l."编号" AND f."状态" = 1
    ) THEN '已审批' ELSE '审批中或未发起' END AS "立项审批状态",
    COALESCE((SELECT SUM(a."到账金额") FROM "项目经费到账" a
               JOIN "流程" f ON f."流程模板编号" = 500 AND f."项目编号" = a."编号" AND f."状态" = 1
              WHERE a."流程模板编号" = 410 AND a."项目编号" = l."编号"), 0) AS "已到账金额",
    COALESCE((SELECT SUM(COALESCE(b."批准经费",0) + COALESCE(b."配套经费",0))
                FROM "项目经费预算" b
               WHERE b."流程模板编号" = 410 AND b."项目编号" = l."编号"), 0) AS "预算金额",
    COALESCE((SELECT SUM(r."报销金额") FROM "报销" r
               JOIN "流程" f ON f."流程模板编号" = 600 AND f."项目编号" = r."编号" AND f."状态" = 1
              WHERE r."流程模板编号" = 410 AND r."项目编号" = l."编号"), 0) AS "已报销金额",
    (SELECT COUNT(*) FROM "科研项目过程预警记录" w
      WHERE w."项目编号" = l."编号" AND COALESCE(w."处理状态", '') NOT IN ('已确认','已关闭','已处理/归档')) AS "待处理提醒数",
    CASE WHEN EXISTS (
        SELECT 1 FROM "纵向项目结题" c
         JOIN "流程" f ON f."流程模板编号" = 440 AND f."项目编号" = c."编号" AND f."状态" = 1
        WHERE c."纵向项目编号" = l."编号"
    ) THEN '已结题' WHEN EXISTS (
        SELECT 1 FROM "纵向项目结题" c WHERE c."纵向项目编号" = l."编号"
    ) THEN '结题审批中' ELSE '未结题' END AS "结题状态",
    (SELECT COUNT(*) FROM "成果项目" r
      WHERE r."项目类型" = 410 AND r."项目编号" = l."编号") AS "成果归档数"
FROM "纵向项目立项" l;

UPDATE "系统迁移版本"
   SET "版本" = 117,
       "脚本" = '117_p0_core_mode_lifecycle_and_external_state.sql',
       "检查摘要" = '将基层核心版能力、项目闭环验收、外部接口真实状态和孤立参与人人工复核落到服务端与数据库',
       "应用时间" = CURRENT_TIMESTAMP
 WHERE "编号" = 1;

COMMIT;
