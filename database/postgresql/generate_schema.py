#!/usr/bin/env python3
"""Generate a PostgreSQL table schema from exported SQL Server metadata.

The metadata files are produced from the restored SQL Server backup.  Names are
kept quoted so the existing Chinese table/column contracts remain unchanged.
"""

from __future__ import annotations

import csv
import re
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "source-sqlserver"
OUT = ROOT / "migrations" / "001_schema.sql"


def q(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def rows(name: str) -> list[list[str]]:
    path = SOURCE / name
    with path.open(encoding="utf-8", newline="") as handle:
        return [
            row
            for row in csv.reader(handle, delimiter="\t")
            if row and not row[0].lstrip().startswith("(")
        ]


def pg_type(sql_type: str, max_length: int, precision: int, scale: int) -> str:
    t = sql_type.lower()
    if t in {"nvarchar", "nchar", "varchar", "char", "text", "ntext"}:
        if max_length < 0:
            return "text"
        # SQL Server reports nvarchar length in bytes.
        length = max_length // 2 if t in {"nvarchar", "nchar"} else max_length
        return f"varchar({length})" if length else "text"
    if t in {"int"}:
        return "integer"
    if t in {"bigint"}:
        return "bigint"
    if t in {"smallint"}:
        return "smallint"
    if t in {"tinyint"}:
        return "smallint"
    if t in {"bit"}:
        return "boolean"
    if t in {"decimal", "numeric"}:
        return f"numeric({precision},{scale})"
    if t == "money":
        return "numeric(19,4)"
    if t == "smallmoney":
        return "numeric(10,4)"
    if t == "float":
        return "double precision"
    if t == "real":
        return "real"
    if t in {"datetime", "datetime2", "smalldatetime"}:
        return "timestamp without time zone"
    if t == "date":
        return "date"
    if t in {"time", "datetimeoffset"}:
        return "time with time zone" if t == "time" else "timestamp with time zone"
    if t == "uniqueidentifier":
        return "uuid"
    if t in {"binary", "varbinary", "image"}:
        return "bytea"
    if t == "xml":
        return "xml"
    # User-defined table types do not occur in table columns; retain an
    # explicit text fallback instead of silently losing data.
    return "text"


def default_expression(value: str, sql_type: str) -> str | None:
    value = value.strip()
    if not value:
        return None
    if re.fullmatch(r"\(getdate\(\)\)", value, re.I):
        return "CURRENT_TIMESTAMP"
    value = re.sub(r"^\(+|\)+$", "", value)
    value = value.replace("N'", "'")
    if value.lower() in {"0", "1"} and sql_type.lower() == "bit":
        return "TRUE" if value == "1" else "FALSE"
    return value


def main() -> None:
    table_columns: dict[str, list[list[str]]] = defaultdict(list)
    for row in rows("columns.tsv"):
        if len(row) < 12:
            raise ValueError(f"invalid columns row: {row!r}")
        table_columns[row[0]].append(row)

    primary_keys: dict[str, list[str]] = defaultdict(list)
    for row in rows("primary-keys.tsv"):
        if len(row) >= 6:
            primary_keys[row[0]].append(row[4])

    foreign_keys: list[list[str]] = rows("foreign-keys.tsv")
    if foreign_keys and len(foreign_keys[0]) < 7:
        foreign_keys = []

    output: list[str] = [
        "-- Generated from the restored SQL Server backup.",
        "-- Do not edit this file to apply production data; use the data migration tool.",
        "BEGIN;",
        "SET client_encoding = 'UTF8';",
        "",
    ]

    for table, columns in sorted(table_columns.items()):
        definitions: list[str] = []
        for row in columns:
            _, _, name, sql_t, max_len, precision, scale, nullable, identity, default, seed, increment = row
            definition = f"    {q(name)} {pg_type(sql_t, int(max_len), int(precision), int(scale))}"
            if identity == "1":
                definition += " GENERATED BY DEFAULT AS IDENTITY"
            elif nullable == "0":
                definition += " NOT NULL"
            default_sql = default_expression(default, sql_t)
            if default_sql:
                definition += f" DEFAULT {default_sql}"
            definitions.append(definition)
        pk = primary_keys.get(table, [])
        if pk:
            definitions.append("    CONSTRAINT " + q(f"pk_{table}") + " PRIMARY KEY (" + ", ".join(q(k) for k in pk) + ")")
        output.append(f"CREATE TABLE IF NOT EXISTS {q(table)} (\n" + ",\n".join(definitions) + "\n);\n")

    for row in foreign_keys:
        name, parent_table, parent_col, ref_table, ref_col, delete_action, update_action = row[:7]
        action = ""
        if delete_action == "CASCADE":
            action += " ON DELETE CASCADE"
        if update_action == "CASCADE":
            action += " ON UPDATE CASCADE"
        output.append(
            f"ALTER TABLE {q(parent_table)} ADD CONSTRAINT {q(name)} FOREIGN KEY ({q(parent_col)}) "
            f"REFERENCES {q(ref_table)} ({q(ref_col)}){action};\n"
        )

    output.extend(["COMMIT;", ""])
    OUT.write_text("\n".join(output), encoding="utf-8")
    print(f"generated {OUT} ({len(table_columns)} tables, {sum(len(v) for v in table_columns.values())} columns)")


if __name__ == "__main__":
    main()
